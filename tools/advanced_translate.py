def transliterate(word):
    mapping = {
        "ph": "ف",
        "ch": "چ",
        "sh": "ش",
        "th": "ت",
        "ae": "آ",
        "oe": "و",
        "aa": "آ",
        "c": "ک",
        "k": "ک",
        "q": "ک",
        "x": "کس",
        "a": "آ",
        "b": "ب",
        "d": "د",
        "e": "ه",
        "f": "ف",
        "g": "گ",
        "h": "ه",
        "i": "ی",
        "j": "ج",
        "l": "ل",
        "m": "م",
        "n": "ن",
        "o": "و",
        "p": "پ",
        "r": "ر",
        "s": "س",
        "t": "ت",
        "u": "و",
        "v": "و",
        "w": "و",
        "y": "ی",
        "z": "ز",
    }
    word = word.lower()
    res = ""
    i = 0
    while i < len(word):
        if word[i : i + 2] in ["ph", "ch", "sh", "th", "ae", "oe", "aa"]:
            res += mapping[word[i : i + 2]]
            i += 2
        elif word[i] == "c":
            if i + 1 < len(word) and word[i + 1] in ["e", "i", "y"]:
                res += "س"
            else:
                res += "ک"
            i += 1
        elif word[i] in mapping:
            res += mapping[word[i]]
            i += 1
        else:
            i += 1
    return res


